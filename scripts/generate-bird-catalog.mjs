import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const birds = JSON.parse(readFileSync(join(root, 'catalog', 'birds.zh-CN.json'), 'utf8'));
const output = `// Generated by scripts/generate-bird-catalog.mjs. Edit catalog/birds.zh-CN.json instead.\nimport { BirdSpecies } from '../models/BirdModels';\n\nexport const SPECIES: BirdSpecies[] = ${JSON.stringify(birds, null, 2)};\n`;
writeFileSync(join(root, 'entry', 'src', 'main', 'ets', 'data', 'BirdCatalog.generated.ets'), output);
console.log(`Generated ${birds.length} bird species.`);
